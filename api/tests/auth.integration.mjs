const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const php = 'C:/xampp/php/php.exe'
const databaseName = `tcsa_auth_test_${randomBytes(8).toString('hex')}`
const email = `test.${randomBytes(6).toString('hex')}@example.test`
const password = randomBytes(24).toString('base64url')
let scratch, config, server, base, cookie = '', token = '', limitsUser

function command(args, input = '', env = {}) {
  return new Promise((accept, reject) => {
    const child = spawn(php, args, { cwd: root, windowsHide: true,
      env: { ...process.env, ...env }, stdio: ['pipe', 'pipe', 'pipe'] })
    let stdout = '', stderr = ''
    child.stdout.on('data', value => { stdout += value })
    child.stderr.on('data', value => { stderr += value })
    child.on('error', reject)
    child.on('close', code => {
      if (code !== 0) reject(new Error(`PHP command failed: ${stderr || stdout}`))
      else accept(stdout)
    })
    child.stdin.end(input)
  })
}

async function sql(statement, params = []) {
  return JSON.parse(await command(['-r', `require 'api/lib/settings.php'; $b=json_decode(stream_get_contents(STDIN),true,8,JSON_THROW_ON_ERROR); $q=database()->prepare($b['sql']); $q->execute($b['params']); echo json_encode($q->fetchAll());`],
    JSON.stringify({ sql: statement, params }), { APP_CONFIG_FILE: config }))
}

async function request(path, { method = 'GET', body, csrf = token, headers = {}, withCookie = cookie } = {}) {
  const response = await fetch(base + path, { method, headers: { Cookie: withCookie,
    ...(method === 'POST' ? { 'X-CSRF-Token': csrf, Origin: 'http://127.0.0.1:5173' } : {}),
    ...(body !== undefined ? { 'Content-Type': 'application/json' } : {}), ...headers },
    body: body === undefined ? undefined : typeof body === 'string' ? body : JSON.stringify(body) })
  const setCookie = response.headers.get('set-cookie')
  if (setCookie) cookie = setCookie.split(';')[0]
  const result = await response.json()
  return { response, result, setCookie }
}

async function session() {
  const result = await request('/api/auth/session.php')
  assert.equal(result.response.status, 200)
  token = result.result.data.csrfToken
  return result
}

async function login() {
  const result = await request('/api/auth/login.php', { method: 'POST', body: { email: email.toUpperCase(), password } })
  assert.equal(result.response.status, 200)
  token = result.result.data.csrfToken
  return result
}

before(async () => {
  scratch = await mkdtemp(join(tmpdir(), 'tcsa-auth-check-'))
  config = join(scratch, 'auth.local')
  await command(['api/bin/setup-local.php', `--database=${databaseName}`, `--config=${config}`])
  await writeFile(config, (await readFile(config, 'utf8')) + `SESSION_NAME="TCSA_TEST_SESSION"\nSESSION_PATH="${join(scratch, 'sessions').replaceAll('\\', '/')}"\n`)
  const values = await readFile(config, 'utf8')
  limitsUser = values.match(/^DB_USER="([a-z0-9_]+)"/m)[1]
  await command(['api/bin/create-staff.php'], JSON.stringify({ email, name: 'Staff Tester', password }), { APP_CONFIG_FILE: config })
  const portReservation = createServer()
  await new Promise(accept => portReservation.listen(0, '127.0.0.1', accept))
  const port = portReservation.address().port
  await new Promise(accept => portReservation.close(accept))
  base = `http://127.0.0.1:${port}`
  server = spawn(php, ['-d', 'display_errors=0', '-S', `127.0.0.1:${port}`, '-t', 'api', 'api/serve.php'],
    { cwd: root, env: { ...process.env, APP_CONFIG_FILE: config }, windowsHide: true, stdio: 'ignore' })
  for (let attempt = 0; attempt < 40; attempt++) {
    try { if ((await fetch(base + '/api/health.php')).ok) return }
    catch { /* Wait for this isolated PHP listener only. */ }
    if (server.exitCode !== null) throw new Error('Test PHP server exited.')
    await new Promise(accept => setTimeout(accept, 100))
  }
  throw new Error('Test PHP server did not start.')
})

after(async () => {
  if (server && server.exitCode === null) {
    await new Promise(accept => { server.once('exit', accept); server.kill() })
  }
  if (limitsUser) {
    // These names were freshly generated by this test run, never application data.
    assert.match(databaseName, /^tcsa_auth_test_[a-f0-9]{16}$/)
    assert.match(limitsUser, /^tcsa_auth_[a-f0-9]{8}$/)
    await command(['-r', `$b=json_decode(stream_get_contents(STDIN),true); $p=new PDO('mysql:host=127.0.0.1;port=3306;charset=utf8mb4',getenv('TCSA_SETUP_USER')?:'root',getenv('TCSA_SETUP_PASSWORD')?:'',[PDO::ATTR_ERRMODE=>PDO::ERRMODE_EXCEPTION]); $p->exec('DROP DATABASE \`'.$b['database'].'\`'); $p->exec('DROP USER '.$p->quote($b['user'])."@'localhost'");`],
      JSON.stringify({ database: databaseName, user: limitsUser }))
  }
  if (scratch) {
    const absolute = resolve(scratch)
    assert.equal(dirname(absolute), resolve(tmpdir()))
    assert.match(basename(absolute), /^tcsa-auth-check-[A-Za-z0-9]+$/)
    await rm(absolute, { recursive: true, force: true })
  }
})

test('signed-out requests are blocked and the form receives a protected cookie/token', async () => {
  const anon = await session()
  assert.equal(anon.result.data.user, null)
  assert.match(token, /^[a-f0-9]{64}$/)
  assert.match(anon.setCookie, /HttpOnly/i)
  assert.match(anon.setCookie, /SameSite=Lax/i)
  assert.match(anon.setCookie, /path=\/api/i)
  assert.equal(anon.response.headers.get('cache-control'), 'no-store')
  const me = await request('/api/auth/me.php')
  assert.equal(me.response.status, 401)
})

test('request validation rejects bad methods, JSON, field types and CSRF/origin', async () => {
  assert.equal((await request('/api/auth/login.php')).response.status, 405)
  assert.equal((await request('/api/auth/login.php', { method: 'POST', body: { email, password }, csrf: '' })).response.status, 403)
  assert.equal((await request('/api/auth/login.php', { method: 'POST', body: { email, password }, headers: { Origin: 'https://other.example' } })).response.status, 403)
  assert.equal((await request('/api/auth/login.php', { method: 'POST', body: '{' })).response.status, 400)
  assert.equal((await request('/api/auth/login.php', { method: 'POST', body: [] })).response.status, 400)
  assert.equal((await request('/api/auth/login.php', { method: 'POST', body: { email: {}, password } })).response.status, 422)
  assert.equal((await request('/api/auth/login.php', { method: 'POST', body: { email, password: [] } })).response.status, 422)
  assert.equal((await request('/api/auth/login.php', { method: 'POST', body: { email, password: 'x'.repeat(1025) } })).response.status, 422)
  assert.equal((await request('/api/auth/login.php', { method: 'POST', body: 'x'.repeat(8193) })).response.status, 413)
})

test('wrong passwords and unknown accounts use the same safe message', async () => {
  const known = await request('/api/auth/login.php', { method: 'POST', body: { email, password: 'incorrect-password' } })
  const unknown = await request('/api/auth/login.php', { method: 'POST', body: { email: 'missing@example.test', password: 'incorrect-password' } })
  assert.equal(known.response.status, 401)
  assert.equal(unknown.response.status, 401)
  assert.equal(known.result.message, unknown.result.message)
  assert.equal((await session()).result.data.user, null)
})

test('email sign-in rotates the session, survives requests and returns no secrets', async () => {
  const anonymousCookie = cookie
  const anonymousToken = token
  const success = await login()
  assert.notEqual(cookie, anonymousCookie)
  assert.notEqual(token, anonymousToken)
  assert.deepEqual(Object.keys(success.result.data.user).sort(), ['email', 'id', 'name'])
  assert.equal(success.result.data.user.email, email)
  assert.equal((await session()).result.data.user.name, 'Staff Tester')
  assert.equal((await request('/api/auth/me.php')).response.status, 200)
  const signedInCookie = cookie
  assert.equal((await request('/api/auth/me.php', { withCookie: anonymousCookie })).response.status, 401)
  cookie = signedInCookie
})

test('passwords are Argon2id hashes and account creation does not reset an existing account', async () => {
  const check = JSON.parse(await command(['-r', `require 'api/lib/settings.php'; $b=json_decode(stream_get_contents(STDIN),true); $q=database()->prepare('SELECT password_hash FROM staff_users WHERE email=?'); $q->execute([$b['email']]); $h=$q->fetchColumn(); echo json_encode(['algorithm'=>password_get_info($h)['algoName'],'valid'=>password_verify($b['password'],$h)]);`],
    JSON.stringify({ email, password }), { APP_CONFIG_FILE: config }))
  assert.equal(check.algorithm, 'argon2id')
  assert.equal(check.valid, true)
  await assert.rejects(command(['api/bin/create-staff.php'], JSON.stringify({ email, name: 'Overwrite', password }), { APP_CONFIG_FILE: config }))
})

test('logout invalidates the old authenticated session and old form token', async () => {
  const oldCookie = cookie, oldToken = token
  assert.equal((await request('/api/auth/logout.php', { method: 'POST', csrf: '' })).response.status, 403)
  const loggedOut = await request('/api/auth/logout.php', { method: 'POST' })
  assert.equal(loggedOut.response.status, 200)
  assert.equal(loggedOut.result.data.user, null)
  token = loggedOut.result.data.csrfToken
  assert.notEqual(cookie, oldCookie)
  assert.equal((await request('/api/auth/me.php', { withCookie: oldCookie })).response.status, 401)
  await session()
  assert.equal((await request('/api/auth/login.php', { method: 'POST', csrf: oldToken, body: { email, password } })).response.status, 403)
})

test('disabled accounts lose existing sessions and cannot sign in', async () => {
  await login()
  await sql('UPDATE staff_users SET is_active = 0 WHERE email = ?', [email])
  assert.equal((await request('/api/auth/me.php')).response.status, 401)
  await session()
  assert.equal((await request('/api/auth/login.php', { method: 'POST', body: { email, password } })).response.status, 401)
  await sql('UPDATE staff_users SET is_active = 1 WHERE email = ?', [email])
})

test('inactivity and absolute session expiry are enforced on the server', async () => {
  for (const [field, age] of [['last_seen', 1801], ['signed_in_at', 28801]]) {
    await login()
    const sid = cookie.split('=')[1]
    assert.match(sid, /^[a-zA-Z0-9,-]+$/)
    const path = join(scratch, 'sessions', `sess_${sid}`)
    const serialized = await readFile(path, 'utf8')
    await writeFile(path, serialized.replace(new RegExp(`${field}\\|i:\\d+;`), `${field}|i:${Math.floor(Date.now() / 1000) - age};`))
    assert.equal((await request('/api/auth/me.php')).response.status, 401)
    await session()
  }
})

