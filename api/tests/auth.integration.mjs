test('per-account and per-IP rate limits block repeated failures, then expire', async () => {
  await sql('DELETE FROM auth_login_limits')
  for (let attempt = 0; attempt < 10; attempt++) {
    assert.equal((await request('/api/auth/login.php', { method: 'POST', body: { email, password: 'bad-password' } })).response.status, 401)
  }
  const accountLimit = await request('/api/auth/login.php', { method: 'POST', body: { email, password } })
  assert.equal(accountLimit.response.status, 429)
  assert.ok(Number(accountLimit.response.headers.get('retry-after')) > 0)
  for (let attempt = 0; attempt < 20; attempt++) {
    assert.equal((await request('/api/auth/login.php', { method: 'POST', body: { email: `missing${attempt}@example.test`, password: 'bad-password' } })).response.status, 401)
  }
  assert.equal((await request('/api/auth/login.php', { method: 'POST', body: { email: 'another@example.test', password } })).response.status, 429)
  await sql('UPDATE auth_login_limits SET window_start = ?', [Math.floor(Date.now() / 1000) - 901])
  await login()
})
